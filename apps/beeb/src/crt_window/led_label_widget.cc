LedLabelWidget::LedLabelWidget(const std::string& text, QWidget *parent)
    : QWidget(parent) //
    , is_on_{false} //
{
  text_ = new QLabel(this);
  QFont font{"Arial", 7};
  text_->setFont(font);
  text_->setText(QString::fromStdString(text));
  text_->setAlignment(Qt::AlignmentFlag::AlignHCenter | Qt::AlignmentFlag::AlignTop);

  QImage img(16, 16, QImage::Format_ARGB32);
  memcpy(img.bits(), LED_ON_DATA.data(), 16 * 16 * 4);
  led_on_pixmap_ = QPixmap::fromImage(img);

  memcpy(img.bits(), LED_OFF_DATA.data(), 16 * 16 * 4);
  led_off_pixmap_ = QPixmap::fromImage(img);

  led_ = new QLabel(this);
  led_->setPixmap(led_off_pixmap_);
  led_->resize(led_off_pixmap_.size());
  led_->setAlignment(Qt::AlignmentFlag::AlignHCenter);

  auto layout = new QVBoxLayout(this);
  layout->addWidget(led_);
  layout->addWidget(text_);
  layout->setContentsMargins(0,0,0,0);
  setLayout(layout);
}

void LedLabelWidget::turn_on() {
  is_on_ = true;
  led_->setPixmap(led_on_pixmap_);
}

void LedLabelWidget::turn_off() {
  is_on_ = false;
  led_->setPixmap(led_off_pixmap_);
}
